"""Inspect actual static HTML links, fragments and canonical navigation."""
from html.parser import HTMLParser
import os
import re
import json
import hashlib
import xml.etree.ElementTree as ET
from pathlib import Path
from urllib.parse import unquote, urlsplit

MARKER = '<!-- Generated from canonical Markdown. Do not edit this file directly. -->'


class Page(HTMLParser):
    """Collect semantic navigation and resources without interpreting script strings."""

    def __init__(self, text):
        super().__init__(convert_charrefs=True)
        self.ids = set()
        self.links = []
        self.nav_links = []
        self.nav_headings = []
        self.in_nav = False
        self.heading = None
        self.anchor = None
        self.content_heading = False
        self.in_content = False
        self.scripts = []
        self.metadata = {}
        self.canonical = None
        self.images = []
        self.h1_count = 0
        self.feed(text)

    def handle_starttag(self, tag, attributes):
        """Read IDs, link destinations and sidebar identity from real elements."""
        attrs = dict(attributes)
        if tag == 'meta':
            self.metadata[attrs.get('name') or attrs.get('property')] = attrs.get('content', '')
        if tag == 'link' and attrs.get('rel') == 'canonical':
            self.canonical = attrs.get('href')
        if tag == 'img':
            self.images.append(attrs)
        if tag == 'h1':
            self.h1_count += 1
        if attrs.get('id'):
            self.ids.add(attrs['id'])
        if attrs.get('id') == 'docNav':
            self.in_nav = True
        if attrs.get('id') == 'content':
            self.in_content = True
        if self.in_content and tag == 'h1':
            self.content_heading = True
        for attribute in ('href', 'src', 'poster'):
            if attrs.get(attribute):
                self.links.append(attrs[attribute])
        if tag == 'script':
            self.scripts.append(attrs.get('src', 'inline'))
        if self.in_nav and tag == 'h2':
            self.heading = ''
        if self.in_nav and tag == 'a':
            self.anchor = [attrs.get('href'), '']

    def handle_data(self, data):
        """Accumulate displayed labels, including inline markup."""
        if self.heading is not None:
            self.heading += data
        if self.anchor is not None:
            self.anchor[1] += data

    def handle_endtag(self, tag):
        """Finish the sidebar's headings and links at their semantic boundaries."""
        if tag == 'aside':
            self.in_nav = False
        if tag == 'h2' and self.heading is not None:
            self.nav_headings.append(self.heading.strip())
            self.heading = None
        if tag == 'a' and self.anchor is not None:
            self.nav_links.append((self.anchor[0], self.anchor[1].strip()))
            self.anchor = None


def validate_static_docs(root: Path, canonical_navigation, failures: list[str]) -> None:
    """Extend DOC-130 ownership guards with rendered navigation and actual HTML IDs."""
    docs = root / 'docs'
    resolved_docs = docs.resolve()
    cache = {}
    link_targets = {}
    for file in sorted(docs.rglob('*.html')):
        cache[file.resolve()] = Page(file.read_text(encoding='utf-8'))
    manifest = json.loads((docs / 'stable/manifest.json').read_text(encoding='utf-8'))
    stable_navigation = []
    for heading, body in re.findall(r'^## ([^\n]+)\n(.*?)(?=^## |\Z)', manifest['user_index'], re.MULTILINE | re.DOTALL):
        # Only listed user pages form navigation; prose links can point to developer docs.
        entries = [(md, title) for title, md in re.findall(
            r'^\s*(?:[-+*]|\d+[.)])\s+\[([^\]]+)\]\(([a-z\d_-]+\.md)\)',
            body, re.MULTILINE | re.IGNORECASE)]
        if entries:
            stable_navigation.append((heading, entries))
    generated_files = []
    for channel, navigation in [('next', canonical_navigation), ('stable', stable_navigation)]:
        expected_links = [(Path(md).with_suffix('.html').name, title)
                          for _, entries in navigation for md, title in entries]
        expected_groups = [heading for heading, _ in navigation]
        for route, _ in expected_links:
            file = docs / channel / route
            if not file.is_file():
                failures.append(f'public user route is missing: {channel}/{route}')
                continue
            page = cache[file.resolve()]
            if page.nav_headings != expected_groups or page.nav_links != expected_links:
                failures.append(f'{channel}/{route} navigation must mirror canonical index sections, titles and order')
        generated_files += [docs / channel / route for route, _ in expected_links]
        generated_files += [docs / channel / 'documentation.html']
    stable_pages = {Path(md).with_suffix('.html').name for _, entries in stable_navigation for md, _ in entries}
    next_pages = {Path(md).with_suffix('.html').name for _, entries in canonical_navigation for md, _ in entries}
    for route in sorted(stable_pages | next_pages | {'documentation.html'}):
        file = docs / route
        if not file.is_file():
            failures.append(f'public user route is missing: {route}')
            continue
        target = f"{'stable' if route in stable_pages or route == 'documentation.html' else 'next'}/{route}"
        text = file.read_text(encoding='utf-8')
        if f'location.replace("{target}"' not in text or f'href="{target}"' not in text:
            failures.append(f'{route} compatibility target must be {target}')
        generated_files.append(file)
    artifact_names = set(manifest['artifacts'])
    actual_names = {file.relative_to(docs / 'stable').as_posix() for file in (docs / 'stable').rglob('*') if file.is_file()}
    if actual_names != artifact_names | {'manifest.json'}:
        failures.append('Stable has missing or extra files')
    if set(manifest['pages']) != stable_pages | {'documentation.html'}:
        failures.append('Stable inventory differs from its release user index')
    for name, digest in manifest['artifacts'].items():
        file = docs / 'stable' / name
        if file.is_file() and hashlib.sha256(file.read_bytes()).hexdigest() != digest:
            failures.append(f'Stable hash mismatch: {name}')
    generated_files += [file.with_suffix('.html') for file in (docs / 'developer').rglob('*.md')]
    generated_files += [docs / name for name in ('doc.html', 'build.html', 'repository_layout.html')]
    for file in generated_files:
        if not file.is_file():
            failures.append(f'missing generated static route: {file.relative_to(root)}')
            continue
        text = file.read_text(encoding='utf-8')
        page = cache[file.resolve()]
        if MARKER not in text:
            failures.append(f'{file.relative_to(root)} is missing generated marker')
        if 'loadMarkdown(' in text or 'marked.min.js' in text or 'docs-shell.js' in text:
            failures.append(f'{file.relative_to(root)} retains runtime Markdown rendering')
        compatibility = file.parent == docs
        if not compatibility and (not page.content_heading or 'docNav' not in page.ids):
            failures.append(f'{file.relative_to(root)} lacks static content/navigation')
        if file.is_relative_to(docs / 'developer'):
            developer_index = Path(os.path.relpath(docs / 'developer/index.html', file.parent)).as_posix()
            user_hub = Path(os.path.relpath(docs / 'next/documentation.html', file.parent)).as_posix()
            if page.nav_links != [(user_hub, 'User Documentation'), (developer_index, 'Developer Documentation')]:
                failures.append(f'{file.relative_to(root)} has incorrect developer navigation')
        for link in page.links:
            parsed = urlsplit(link)
            if parsed.scheme or parsed.netloc:
                continue
            candidate = file.parent / unquote(parsed.path) if parsed.path else file
            # Repeated sidebar/assets share targets; cache only within this validation.
            if candidate not in link_targets:
                target = candidate.resolve()
                link_targets[candidate] = (target, target.is_relative_to(resolved_docs) and target.is_file())
            target, exists = link_targets[candidate]
            if not exists:
                failures.append(f'{file.relative_to(root)} has missing generated link/resource: {link}')
            elif parsed.fragment and target in cache and unquote(parsed.fragment) not in cache[target].ids:
                failures.append(f'{file.relative_to(root)} has missing generated fragment: {link}')
    hub = (docs / 'next/documentation.html').read_text(encoding='utf-8')
    for marker in ('class="developer-entry"', 'href="../developer/index.html"', 'id="docGrid"'):
        if marker not in hub:
            failures.append(f'next/documentation.html is missing required marker: {marker}')
    if list((docs / 'user').rglob('*.html')):
        failures.append('localized mirrors or user source directories unexpectedly publish HTML')
    validate_web_metadata(docs, cache, manifest, failures)


def validate_web_metadata(docs, cache, manifest, failures):
    """Check real XML and HTML semantics while respecting the frozen Stable template."""
    origin = 'https://perastage.luismaperamato.com/'
    resolved_docs = docs.resolve()
    expected = {origin}
    for file, page in cache.items():
        route = file.relative_to(resolved_docs).as_posix()
        if route.startswith('stable/'):
            if route in {'stable/' + name for name in manifest['pages']}:
                if page.canonical != origin + route:
                    failures.append(f'{route} has incorrect frozen Stable canonical')
                if 'noindex' not in page.metadata.get('robots', ''):
                    expected.add(origin + route)
            continue
        text = file.read_text(encoding='utf-8')
        if 'Compatibility-only' in text:
            if page.metadata.get('robots') != 'noindex,follow':
                failures.append(f'{route} compatibility page must remain noindex')
            if page.canonical and not page.canonical.startswith(origin):
                failures.append(f'{route} compatibility canonical must be absolute')
            continue
        if route == '404.html':
            if page.metadata.get('robots') != 'noindex,follow' or page.h1_count != 1:
                failures.append('404 must have one h1 and remain noindex')
            continue
        canonical = origin if route == 'index.html' else origin + route
        if page.canonical != canonical:
            failures.append(f'{route} canonical must be {canonical}')
        for field in ('description', 'og:site_name', 'og:type', 'og:title', 'og:description',
                      'og:url', 'og:image', 'twitter:card', 'twitter:title',
                      'twitter:description', 'twitter:image'):
            if not page.metadata.get(field):
                failures.append(f'{route} missing metadata: {field}')
        description = page.metadata.get('description', '')
        if not 120 <= len(description) <= 170 or '<' in description or '\n' in description:
            failures.append(f'{route} requires a concise plain-text description')
        if page.metadata.get('og:url') != canonical or page.metadata.get('twitter:card') != 'summary_large_image':
            failures.append(f'{route} has incorrect social URL/card')
        for field in ('og:image', 'twitter:image'):
            if not page.metadata.get(field, '').startswith(origin):
                failures.append(f'{route} requires absolute social image URLs')
        if route.startswith('next/') and page.metadata.get('robots') != 'noindex,follow':
            failures.append(f'{route} Next must remain noindex,follow')
        if route.startswith('developer/') and 'noindex' not in page.metadata.get('robots', ''):
            expected.add(canonical)
        if page.h1_count != 1:
            failures.append(f'{route} must have exactly one primary h1')
        for image in page.images:
            if 'alt' not in image:
                failures.append(f'{route} image requires explicit alt behavior')
    try:
        sitemap = ET.parse(docs / 'sitemap.xml')
        namespace = '{http://www.sitemaps.org/schemas/sitemap/0.9}'
        assert sitemap.getroot().tag == namespace + 'urlset'
        urls = [node.text for node in sitemap.findall(f'{namespace}url/{namespace}loc')]
        assert urls == sorted(expected), 'sitemap inventory/order must match indexable canonical routes'
        assert all(url.startswith(origin) for url in urls)
        assert not sitemap.findall(f'{namespace}url/{namespace}lastmod')
    except (ET.ParseError, AssertionError, OSError) as error:
        failures.append(f'invalid sitemap: {error}')
