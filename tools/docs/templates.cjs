const path = require('node:path');
const marked = require('./vendor/marked.min.js');
const { metadata } = require('./metadata.cjs');
const { publicUrl } = require('./site.cjs');
const { escapeHtml: e, relativeUrl } = require('./render_markdown.cjs');

const MARKER = '<!-- Generated from canonical Markdown. Do not edit this file directly. -->';

// Emit a complete readable shell whose only enhancement is mobile navigation.
function pageTemplate(page, content, context, hub = false) {
  const url = target => e(relativeUrl(page.output, target));
  const docUrl = filename => url(path.join(context.siteDocs || context.docs, filename));
  const developerUrl = context.developerHref ? e(context.developerHref) : url(context.developerIndex);
  const navigation = page.developer ? `<ul class="nav-links">
<li><a href="${url(context.hub)}">User Documentation</a></li>
<li><a href="${developerUrl}">Developer Documentation</a></li>
</ul>` : context.groups.map((group, index) => `<section class="nav-group" aria-labelledby="nav-section-${index}">
<h2 id="nav-section-${index}">${e(group.title)}</h2>
<ul class="nav-links">${group.pages.map(entry => `<li><a${entry.output === page.output ? ' class="active" aria-current="page"' : ''} href="${url(entry.output)}">${e(entry.title)}</a></li>`).join('\n')}</ul>
</section>`).join('\n');
  const breadcrumb = hub ? 'User Documentation' : `${page.developer ? `<a href="${developerUrl}">Developer</a>` : e(page.section)} / <span id="pageTitle">${e(page.title)}</span>`;
  const channel = page.developer ? '' : context.channel;
  const route = path.basename(page.output);
  const other = channel === 'stable' ? 'next' : 'stable';
  const counterpart = channel && context.otherPages.has(route);
  const switcher = !channel ? '' : `<div class="doc-channel">
<span class="channel-label">${channel === 'stable' ? `Stable ${e(context.version)}` : 'Next'}</span>
<nav aria-label="Documentation version" class="channel-switcher"><a href="${url(page.output)}" aria-current="page">${channel === 'stable' ? 'Stable' : 'Next'}</a><a href="${docUrl(`${other}/${counterpart ? route : 'documentation.html'}`)}">${other === 'stable' ? 'Stable' : 'Next'}</a></nav>
${channel === 'next' ? '<p>Development documentation — may describe unreleased changes.</p>' : ''}
${!counterpart ? `<p>This page is unavailable in ${other === 'stable' ? `Stable ${e(context.stableVersion)}` : 'Next'}; the switch opens its documentation overview.</p>` : ''}
</div>`;
  return `<!doctype html>
${MARKER}
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Perastage Documentation • ${e(page.title)}</title>${channel === 'next' ? '\n<meta name="robots" content="noindex,follow" />' : ''}
${metadata(page, context, e)}
<link rel="icon" href="${docUrl('assets/images/favicon.png')}" type="image/png" />
<link rel="apple-touch-icon" href="${docUrl('assets/images/apple-touch-icon.png')}" />
<link rel="stylesheet" href="${docUrl('assets/css/style.css')}" />
<script src="${docUrl('assets/js/docs-nav.js')}" defer></script>
</head>
<body id="top">
<a href="#content" class="skip-link">Skip to content</a>
<div class="page-shell">
<header class="site-header">
<a class="brand" href="${docUrl('index.html')}" aria-label="Perastage home">
<img src="${docUrl('assets/images/logo-web.png')}" alt="" width="48" height="48" />
<div><span class="product-brand-name">Perastage</span><p>MVR &amp; GDTF workflows</p></div>
</a>
<button id="menuToggle" class="menu-toggle" aria-expanded="false" aria-controls="docNav" hidden>Menu</button>
</header>
<div class="layout">
<aside id="docNav" class="nav-panel"><nav aria-label="Documentation navigation">${navigation}</nav></aside>
<main class="content-panel">
<nav class="breadcrumb" aria-label="Breadcrumb"><a href="${url(context.hub)}">Documentation</a> / ${breadcrumb}</nav>${switcher ? '\n' + switcher : ''}
<div id="content" tabindex="-1">${content}</div>
<a class="back-top" href="#top">Back to top</a>
</main>
</div>
<footer>Perastage documentation • <a href="https://github.com/PeramatoG/Perastage">Main GitHub repository</a> • <a href="https://github.com/PeramatoG/Perastage/releases/latest">Latest releases</a></footer>
</div>
</body>
</html>
`;
}

// Derive hub cards and headings from the same navigation and canonical page prose.
function hubContent(context, rendered) {
  const slugger = new marked.Slugger();
  return `<h1 id="user-documentation">User Documentation</h1>
<div id="docGrid">${context.groups.map(group => {
    const id = e(slugger.slug(group.title));
    return `<section aria-labelledby="${id}">
<h2 id="${id}">${e(group.title)}</h2>
<div class="doc-grid">${group.pages.map(page => `<a class="doc-card" href="${e(relativeUrl(context.hub, page.output))}"><span class="doc-card-title">${e(page.title)}</span><span>${rendered.get(page.source).summaryHtml}</span></a>`).join('\n')}</div>
</section>`;
  }).join('\n')}</div>
<section class="developer-entry" aria-labelledby="developer-documentation">
<h2 id="developer-documentation"><a href="${e(context.developerHref || relativeUrl(context.hub, context.developerIndex))}">Developer Documentation</a></h2>
<p>Source builds, architecture, integrations, packaging, and maintainer technical contracts.</p>
</section>
`;
}

// Keep old bookmarks as small redirect consumers of the discovered canonical routes.
function compatibilityTemplate(target, routes, base = '') {
  const fallback = target || 'developer/index.html';
  const script = target ? `location.replace(${JSON.stringify(target)} + location.search + location.hash);` : `
// Compatibility only: accept exact canonical paths, never arbitrary navigation.
const routes = ${JSON.stringify(routes).replace(/</g, '\\u003c')};
const parameters = new URLSearchParams(location.search);
const requested = parameters.get('md') || '';
parameters.delete('md');
const match = requested.match(/^([^#]+)(#[^]*)?$/);
const pathname = match ? match[1] : '';
const safe = !pathname.split('/').some(part => !part || part === '.' || part === '..') && !/[\\\\:\\x00-\\x1f]/.test(pathname);
const destination = safe && Object.prototype.hasOwnProperty.call(routes, pathname) ? routes[pathname] : '${fallback}';
const fragment = location.hash || (match ? match[2] || '' : '');
const query = parameters.toString();
location.replace(destination + (query ? '?' + query : '') + fragment);`;
  return `<!doctype html>
${MARKER}
<!-- Compatibility-only redirect; this page never renders Markdown. -->
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>Perastage Documentation • Page moved</title>
<meta name="robots" content="noindex,follow" />
<link rel="icon" href="${base ? '../' : ''}assets/images/favicon.png" type="image/png" />
${target ? `<link rel="canonical" href="${e(publicUrl(base + fallback))}" />` : ''}
</head>
<body>
<h1>Documentation has moved</h1>
<p>This compatibility page preserves older bookmarks. Continue to <a href="${e(fallback)}">${fallback.startsWith('developer/') ? 'Developer Documentation' : 'User Documentation'}</a>${fallback.startsWith('developer/') ? ' or <a href="documentation.html">User Documentation</a>' : ''}.</p>
<script>${script}
</script>
</body>
</html>
`;
}

module.exports = { MARKER, pageTemplate, hubContent, compatibilityTemplate };
